/**
 * Safely retrieve the cities list for any Indian state or union territory.
 * Handles direct matches, case-insensitive matches, aliases, and partial matches.
 */
export function getCitiesForState(stateName) {
  if (!stateName || typeof stateName !== 'string') return [];
  const clean = stateName.trim();
  if (!clean) return [];

  // 1. Direct match
  if (INDIAN_CITIES_BY_STATE[clean]) {
    return INDIAN_CITIES_BY_STATE[clean];
  }

  // 2. Alias match
  const lower = clean.toLowerCase();
  const aliasKey = STATE_ALIASES[lower];
  if (aliasKey && INDIAN_CITIES_BY_STATE[aliasKey]) {
    return INDIAN_CITIES_BY_STATE[aliasKey];
  }

  // 3. Case-insensitive exact match
  const foundKey = Object.keys(INDIAN_CITIES_BY_STATE).find(
    (key) => key.toLowerCase() === lower
  );
  if (foundKey) {
    return INDIAN_CITIES_BY_STATE[foundKey];
  }

  // 4. Loose substring match (e.g. user selected "Delhi (NCT)")
  const looseKey = Object.keys(INDIAN_CITIES_BY_STATE).find((key) => {
    const kLower = key.toLowerCase();
    return lower.includes(kLower) || kLower.includes(lower);
  });
  if (looseKey) {
    return INDIAN_CITIES_BY_STATE[looseKey];
  }

  return [];
}

